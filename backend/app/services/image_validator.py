"""Image validation and default/placeholder detection service.

Detects municipal error placeholder banners ('IMAGE NOT AVAILABLE'),
synthetic fallback frames, header mismatches, and corrupted or truncated frame payloads.
Used to filter out cameras that are returning default/offline mock images so they are
temporarily skipped during AI flood analysis.
"""

import hashlib
import io
import logging
import os
from typing import Set
from PIL import Image

logger = logging.getLogger("floodwheel.image_validator")


class ImageValidator:
    """Multi-factor image payload validator and default frame detector."""

    # Exact hash signatures of known error banners & default synthetic frames
    KNOWN_ERROR_MD5: Set[str] = {
        "9653ea117b2c39d4c477b0949f95860e",  # Municipal 'IMAGE NOT AVAILABLE' PNG banner
        "b107ef1b97a1eae7a3345879b133299e",  # Default synthetic JPEG frame (snapshot (1).jpeg)
    }
    KNOWN_ERROR_SHA256: Set[str] = {
        "44246c5dfb69d91cffde872630d789488bf0e603ceda9c53b1984185aec4ffba",  # Municipal error banner
        "e2da96a01715c2e4f937db4554d7ca7750b522b890e0fd75d7c64dfd84bc3a7d",  # Default synthetic frame
    }

    # Binary magic headers
    PNG_MAGIC: bytes = b"\x89PNG\r\n\x1a\n"
    JPEG_MAGIC: bytes = b"\xff\xd8"

    MIN_VALID_SIZE_BYTES: int = 500
    MAX_ERROR_PNG_SIZE_BYTES: int = 8000

    @classmethod
    def get_known_error_md5(cls) -> Set[str]:
        """Returns known error MD5 hashes including any configured via ENV."""
        hashes = set(cls.KNOWN_ERROR_MD5)
        extra = os.getenv("KNOWN_ERROR_MD5") or os.getenv("EXTRA_ERROR_MD5")
        if extra:
            hashes.update(h.strip().lower() for h in extra.split(",") if h.strip())
        return hashes

    @classmethod
    def get_known_error_sha256(cls) -> Set[str]:
        """Returns known error SHA256 hashes including any configured via ENV."""
        hashes = set(cls.KNOWN_ERROR_SHA256)
        extra = os.getenv("KNOWN_ERROR_SHA256") or os.getenv("EXTRA_ERROR_SHA256")
        if extra:
            hashes.update(h.strip().lower() for h in extra.split(",") if h.strip())
        return hashes

    @classmethod
    def matches_known_error_hash(cls, data: bytes) -> bool:
        """Determines whether a payload matches known error MD5 or SHA256 checksums."""
        if not data:
            return False

        md5_digest = hashlib.md5(data).hexdigest().lower()
        if md5_digest in cls.get_known_error_md5():
            logger.warning("Detected known error hash match (MD5: %s)", md5_digest)
            return True

        sha256_digest = hashlib.sha256(data).hexdigest().lower()
        if sha256_digest in cls.get_known_error_sha256():
            logger.warning("Detected known error hash match (SHA256: %s)", sha256_digest)
            return True

        return False

    @classmethod
    def is_error_placeholder(cls, data: bytes) -> bool:
        """Determines whether a payload is a municipal error placeholder banner.

        Returns True if:
        1. Payload is empty or below minimum valid payload size (< 500 bytes).
        2. Exact MD5 or SHA256 matches known error banner checksums.
        3. Header is a small PNG disguised with .ashx or .jpeg extensions.
        """
        if not data or len(data) < cls.MIN_VALID_SIZE_BYTES:
            return True

        # Factor 1 & 2: Exact MD5 / SHA256 match
        if cls.matches_known_error_hash(data):
            return True

        if data.startswith(cls.PNG_MAGIC) and len(data) <= cls.MAX_ERROR_PNG_SIZE_BYTES:
            return True

        return False

    @classmethod
    def is_default_synthetic_frame(cls, data: bytes) -> bool:
        """Detects whether a payload is a default/synthetic CCTV frame.

        Matches the signature of synthetic frames generated by FloodWheel or camera-backend
        (e.g., /Users/le.van.thanh/Downloads/snapshot (1).jpeg).
        """
        if not data or len(data) < cls.MIN_VALID_SIZE_BYTES:
            return True

        if cls.matches_known_error_hash(data):
            return True

        # Check visual palette of synthetic generator
        try:
            im = Image.open(io.BytesIO(data))
            w, h = im.size
            if (w, h) == (640, 360):
                # Inspect specific coordinates generated by generate_mock_frame:
                # Sky (10, 50) -> RGB(35, 42, 54)
                # Road (10, 180) -> RGB(45, 50, 58)
                # Water reflection (100, 250) -> RGB(38, 62, 78)
                # Bottom banner (10, 345) -> RGB(15, 18, 24)
                p_sky = im.getpixel((10, 50))
                p_road = im.getpixel((10, 180))
                p_water = im.getpixel((100, 250))
                p_bot = im.getpixel((10, 345))

                def _close(p, target, tol=14):
                    return all(abs(a - b) <= tol for a, b in zip(p[:3], target))

                if (
                    _close(p_sky, (35, 42, 54))
                    and _close(p_road, (45, 50, 58))
                    and _close(p_water, (38, 62, 78))
                    and _close(p_bot, (15, 18, 24))
                ):
                    return True
        except Exception:
            pass

        return False

    @classmethod
    def is_default_or_invalid(cls, data: bytes) -> bool:
        """Returns True if the image is an error placeholder or default synthetic image."""
        return cls.is_error_placeholder(data) or cls.is_default_synthetic_frame(data)

    @classmethod
    def is_valid_real_snapshot(cls, data: bytes) -> bool:
        """Returns True if the image is a valid, real camera snapshot from a live CCTV stream."""
        if cls.is_default_or_invalid(data):
            return False

        if not (data.startswith(cls.JPEG_MAGIC) or data.startswith(cls.PNG_MAGIC)):
            return False

        return True
